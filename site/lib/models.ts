const MODEL_BY_ID = Object.fromEntries(MODELS.map(m => [m.id, m]));

/** Look up a model by its variant id. Throws if unknown. */
export function getModel(id: string): ModelDefinition {
  const model = MODEL_BY_ID[id];
  if (!model) throw new Error(`Unknown model: ${id}`);
  return model;
}

/** Safe lookup that returns undefined for unknown ids. */
export function findModel(id: string): ModelDefinition | undefined {
  return MODEL_BY_ID[id];
}

/** Get the brand colour for a model id, defaulting to grey if unknown. */
export function getModelColour(id: string): string {
  const model = MODEL_BY_ID[id];
  return model ? FAMILY_COLOURS[model.family] : '#888';
}

/** Get the display name for a model id, defaulting to the id itself. */
export function getModelName(id: string): string {
  return MODEL_BY_ID[id]?.name || id;
}

/** Get the token cost for a model id. Defaults to 1. */
export function getModelTokenCost(id: string): number {
  return MODEL_BY_ID[id]?.tokenCost ?? 1;
}
