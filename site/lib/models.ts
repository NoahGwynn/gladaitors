// ============================================================================
// Model registry — single source of truth for AI debater models
// ============================================================================
// Adding a new model: add an entry here. Updating a model version: change
// `providerModelId` here. Both work everywhere automatically — the API,
// the form picker, the debate display, the share modal, and the homepage.
// ============================================================================

export type ModelFamily = 'claude' | 'gpt' | 'gemini' | 'user';

export interface ModelDefinition {
  /** The variant id sent over the wire and stored in the database */
  id: string;
  /** The model family — drives colour and which streamer/provider to call */
  family: ModelFamily;
  /** Display name shown in UI */
  name: string;
  /** Version label shown next to the name (e.g. "4.6", "2.5") */
  version: string;
  /** Tier label shown in UI */
  tier: 'standard' | 'premium';
  /** Tokens deducted per argument generated by this model */
  tokenCost: number;
  /** The exact API model identifier sent to the provider's SDK */
  providerModelId: string;
}

